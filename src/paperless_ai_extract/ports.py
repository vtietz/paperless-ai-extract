"""Ports: the interfaces the application layer depends on.

Adapters in `adapters/` implement them; tests use in-memory fakes.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Protocol

from .domain.models import DocumentSnapshot, Item, Taxonomy


class DocumentStore(Protocol):
    """Paperless-ngx (or anything with the same document model)."""

    def ping(self) -> None: ...
    def taxonomy(self) -> Taxonomy: ...
    def document_ids_with_tag(self, tag_id: int, limit: int) -> list[int]: ...
    def document(self, doc_id: int) -> DocumentSnapshot: ...
    def checksum(self, doc_id: int, original: bool) -> str: ...
    def download(self, doc_id: int, original: bool) -> tuple[bytes, str]: ...
    def create_object(self, endpoint: str, name: str) -> Item: ...
    def update_document(self, doc_id: int, fields: dict) -> None: ...
    def set_custom_fields(self, doc_id: int, values: dict[int, object]) -> None: ...
    def modify_tags(self, doc_id: int, add: list[int], remove: list[int]) -> None: ...
    def add_note(self, doc_id: int, text: str) -> None: ...


@dataclass
class LLMResult:
    content: str
    metrics: dict = field(default_factory=dict)


class LLMClient(Protocol):
    def generate_json(self, prompt: str, images: list[bytes], schema: dict) -> LLMResult:
        """Return the model's raw JSON text for one structured request."""

    def check(self) -> str:
        """Verify connectivity and model availability; return a status line."""

    def describe(self) -> dict:
        """Non-secret settings that influence output (cache fingerprint)."""


class PageRenderer(Protocol):
    def render(self, data: bytes, mime: str, pages: int, max_edge: int) -> list[bytes]:
        """PNG images of the first pages; raise UnsupportedInput if impossible."""


class AddressReader(Protocol):
    def read(self, pdf: bytes) -> list[str] | None:
        """Independent OCR readings of the address window, or None if unsuitable."""


class StateStore(Protocol):
    def cached(self, doc_id: int, source_key: str, fingerprint: str) -> dict | None: ...
    def store(self, doc_id: int, source_key: str, fingerprint: str, result: dict, metrics: dict) -> None: ...
    def has_succeeded(self, doc_id: int) -> bool: ...
    def retry_due(self, doc_id: int) -> bool: ...
    def success(self, doc_id: int) -> None: ...
    def failure(self, doc_id: int, error: str, retry_delay: float) -> int: ...
    def reset_attempts(self, doc_id: int) -> None: ...
    def save_proposal(self, doc_id: int, changes: list[dict]) -> None: ...
    def proposal(self, doc_id: int) -> list[dict] | None: ...
    def drop_proposal(self, doc_id: int) -> None: ...
